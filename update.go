const (
	updateRepo          = "Flyinsky2004/nodeseek-go"
	checksumsAssetName  = "checksums.txt"
	maxDownloadSize     = int64(100 << 20) // 100 MiB
	maxChecksumsSize    = int64(1 << 20)   // 1 MiB
	updateHTTPTimeout   = 60 * time.Second
	maxReleaseJSONBytes = int64(4 << 20)
	updateConfirmTTL    = 10 * time.Minute
	updateNonceBytes    = 8
)

var (
	// Overridable in tests so no real GitHub or download endpoint is contacted.
	updateAPIBase    = "https://api.github.com"
	updateHTTPClient = &http.Client{Timeout: updateHTTPTimeout}
	executablePath   = os.Executable
	currentGOOS      = runtime.GOOS
	currentGOARCH    = runtime.GOARCH
)

// ReleaseInfo is the subset of the GitHub release payload the updater needs.
type ReleaseInfo struct {
	TagName    string         `json:"tag_name"`
	Name       string         `json:"name"`
	HTMLURL    string         `json:"html_url"`
	Draft      bool           `json:"draft"`
	Prerelease bool           `json:"prerelease"`
	Assets     []ReleaseAsset `json:"assets"`
}

type ReleaseAsset struct {
	Name               string `json:"name"`
	BrowserDownloadURL string `json:"browser_download_url"`
	Size               int64  `json:"size"`
}

// pendingUpdate is the exact release/asset the user confirmed. The nonce is
// embedded in the callback data; the chat/message/user binding prevents a
// confirmation from being replayed elsewhere.
type pendingUpdate struct {
	Nonce     string
	ChatID    int64
	MessageID int
	UserID    int64
	Tag       string
	AssetName string
	Checksum  string
	Expires   time.Time
}

var pendingUpdates = struct {
	sync.Mutex
	m map[string]*pendingUpdate
}{m: make(map[string]*pendingUpdate)}

type updateResult struct {
	Version       string
	ExecPath      string
	BackupPath    string
	ManualReplace bool
	NewPath       string
}

// assetNameFor returns the exact release asset name for a platform. It must
// stay in sync with .github/workflows/release.yml.
func assetNameFor(goos, goarch string) (string, error) {
	switch goos + "/" + goarch {
	case "linux/amd64", "linux/arm64",
		"darwin/amd64", "darwin/arm64",
		"windows/amd64", "windows/arm64":
	default:
		return "", fmt.Errorf("不支持的平台 %s/%s（支持 linux/darwin/windows 的 amd64/arm64）", goos, goarch)
	}
	name := fmt.Sprintf("%s-%s-%s", appName, goos, goarch)
	if goos == "windows" {
		name += ".exe"
	}
	return name, nil
}

func fetchLatestRelease(ctx context.Context) (*ReleaseInfo, error) {
	return fetchReleaseURL(ctx, updateAPIBase+"/repos/"+updateRepo+"/releases/latest")
}

func fetchReleaseByTag(ctx context.Context, tag string) (*ReleaseInfo, error) {
	return fetchReleaseURL(ctx, updateAPIBase+"/repos/"+updateRepo+"/releases/tags/"+url.PathEscape(tag))
}

// fetchReleaseURL queries GitHub and rejects drafts/prereleases. The "latest"
// endpoint already excludes them; the tag endpoint needs the explicit check.
func fetchReleaseURL(ctx context.Context, apiURL string) (*ReleaseInfo, error) {
	req, err := http.NewRequestWithContext(ctx, http.MethodGet, apiURL, nil)
	if err != nil {
		return nil, fmt.Errorf("创建 GitHub 请求失败: %w", err)
	}
	req.Header.Set("Accept", "application/vnd.github+json")
	req.Header.Set("User-Agent", appName+"/"+version)

	resp, err := updateHTTPClient.Do(req)
	if err != nil {
		return nil, fmt.Errorf("请求 GitHub Release 失败: %w", err)
	}
	defer resp.Body.Close()

	if resp.StatusCode == http.StatusNotFound {
		return nil, fmt.Errorf("仓库 %s 没有找到对应的正式 Release", updateRepo)
	}
	if resp.StatusCode != http.StatusOK {
		body, _ := io.ReadAll(io.LimitReader(resp.Body, 4096))
		return nil, fmt.Errorf("GitHub API 返回 %d: %s", resp.StatusCode, strings.TrimSpace(string(body)))
	}

	var rel ReleaseInfo
	if err := json.NewDecoder(io.LimitReader(resp.Body, maxReleaseJSONBytes)).Decode(&rel); err != nil {
		return nil, fmt.Errorf("解析 GitHub Release 响应失败: %w", err)
	}
	if rel.TagName == "" {
		return nil, fmt.Errorf("GitHub Release 缺少 tag_name")
	}
	if rel.Draft || rel.Prerelease {
		return nil, fmt.Errorf("Release 不是正式版本（draft=%v, prerelease=%v）", rel.Draft, rel.Prerelease)
	}
	return &rel, nil
}

func findReleaseAsset(rel *ReleaseInfo, name string) (*ReleaseAsset, error) {
	for i := range rel.Assets {
		if rel.Assets[i].Name == name {
			return &rel.Assets[i], nil
		}
	}
	return nil, fmt.Errorf("Release %s 中没有找到资源 %s", rel.TagName, name)
}

// parseChecksums parses the sha256sum-compatible checksums.txt generated by
// the release workflow.
func parseChecksums(data []byte) (map[string]string, error) {
	sums := make(map[string]string)
	for _, line := range strings.Split(string(data), "\n") {
		line = strings.TrimSpace(line)
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		fields := strings.Fields(line)
		if len(fields) < 2 {
			continue
		}
		hash := strings.ToLower(fields[0])
		if len(hash) != 64 {
			continue
		}
		if _, err := hex.DecodeString(hash); err != nil {
			continue
		}
		name := filepath.Base(strings.TrimPrefix(fields[1], "*"))
		sums[name] = hash
	}
	if len(sums) == 0 {
		return nil, fmt.Errorf("checksums.txt 为空或格式无法识别")
	}
	return sums, nil
}

func fetchReleaseChecksums(ctx context.Context, rel *ReleaseInfo) (map[string]string, error) {
	asset, err := findReleaseAsset(rel, checksumsAssetName)
	if err != nil {
		return nil, fmt.Errorf("Release 缺少 %s，拒绝安装", checksumsAssetName)
	}
	data, err := downloadBytes(ctx, asset.BrowserDownloadURL, maxChecksumsSize)
	if err != nil {
		return nil, fmt.Errorf("下载 %s 失败: %w", checksumsAssetName, err)
	}
	return parseChecksums(data)
}

func downloadBytes(ctx context.Context, url string, limit int64) ([]byte, error) {
	req, err := http.NewRequestWithContext(ctx, http.MethodGet, url, nil)
	if err != nil {
		return nil, err
	}
	resp, err := updateHTTPClient.Do(req)
	if err != nil {
		return nil, err
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("HTTP %d", resp.StatusCode)
	}
	data, err := io.ReadAll(io.LimitReader(resp.Body, limit+1))
	if err != nil {
		return nil, err
	}
	if int64(len(data)) > limit {
		return nil, fmt.Errorf("响应超过大小限制 %d 字节", limit)
	}
	return data, nil
}

// downloadAndVerify streams the asset into a temporary file in the executable
// directory, hashing while writing. The original executable is untouched.
func downloadAndVerify(ctx context.Context, asset ReleaseAsset, expectedSHA, dir string) (string, error) {
	if asset.Size > maxDownloadSize {
		return "", fmt.Errorf("更新包大小 %d 超过限制 %d", asset.Size, maxDownloadSize)
	}
	req, err := http.NewRequestWithContext(ctx, http.MethodGet, asset.BrowserDownloadURL, nil)
	if err != nil {
		return "", fmt.Errorf("创建下载请求失败: %w", err)
	}
	resp, err := updateHTTPClient.Do(req)
	if err != nil {
		return "", fmt.Errorf("下载更新包失败: %w", err)
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		return "", fmt.Errorf("下载更新包失败: HTTP %d", resp.StatusCode)
	}
	if resp.ContentLength > maxDownloadSize {
		return "", fmt.Errorf("更新包大小 %d 超过限制 %d", resp.ContentLength, maxDownloadSize)
	}

	f, err := os.CreateTemp(dir, ".nodeseek-update-*")
	if err != nil {
		return "", fmt.Errorf("创建临时文件失败: %w", err)
	}
	tmp := f.Name()
	cleanup := func() {
		_ = f.Close()
		_ = os.Remove(tmp)
	}

	h := sha256.New()
	n, err := io.Copy(io.MultiWriter(f, h), io.LimitReader(resp.Body, maxDownloadSize+1))
	if err != nil {
		cleanup()
		return "", fmt.Errorf("写入更新包失败: %w", err)
	}
	if n > maxDownloadSize {
		cleanup()
		return "", fmt.Errorf("更新包超过大小限制 %d 字节", maxDownloadSize)
	}
	if err := f.Sync(); err != nil {
		cleanup()
		return "", fmt.Errorf("同步更新包失败: %w", err)
	}
	if err := f.Close(); err != nil {
		_ = os.Remove(tmp)
		return "", fmt.Errorf("关闭更新包失败: %w", err)
	}

	actual := hex.EncodeToString(h.Sum(nil))
	if !strings.EqualFold(actual, expectedSHA) {
		_ = os.Remove(tmp)
		return "", fmt.Errorf("SHA256 校验失败: 期望 %s，实际 %s", expectedSHA, actual)
	}

	mode := os.FileMode(0755)
	if exe, err := executablePath(); err == nil {
		if info, statErr := os.Stat(exe); statErr == nil {
			mode = info.Mode().Perm() | 0111
		}
	}
	if err := os.Chmod(tmp, mode); err != nil {
		_ = os.Remove(tmp)
		return "", fmt.Errorf("设置可执行权限失败: %w", err)
	}
	return tmp, nil
}

// buildPendingUpdate validates the release and records the exact tag, asset
// name and checksum that the user will confirm.
func buildPendingUpdate(ctx context.Context, rel *ReleaseInfo) (*pendingUpdate, error) {
	if rel == nil {
		return nil, fmt.Errorf("缺少 Release 信息")
	}
	if _, err := parseSemver(rel.TagName); err != nil {
		return nil, fmt.Errorf("Release tag %q 不是有效 SemVer: %w", rel.TagName, err)
	}
	available, _, err := updateAvailability(version, rel.TagName)
	if err != nil {
		return nil, err
	}
	if !available {
		return nil, fmt.Errorf("当前版本 %s 已是最新（最新 %s），不会降级", version, rel.TagName)
	}

	assetName, err := assetNameFor(currentGOOS, currentGOARCH)
	if err != nil {
		return nil, err
	}
	if _, err := findReleaseAsset(rel, assetName); err != nil {
		return nil, err
	}
	sums, err := fetchReleaseChecksums(ctx, rel)
	if err != nil {
		return nil, err
	}
	expected, ok := sums[assetName]
	if !ok {
		return nil, fmt.Errorf("checksums.txt 中缺少 %s 的校验值，拒绝安装", assetName)
	}
	return &pendingUpdate{
		Tag:       rel.TagName,
		AssetName: assetName,
		Checksum:  expected,
		Expires:   time.Now().Add(updateConfirmTTL),
	}, nil
}

func newUpdateNonce() (string, error) {
	b := make([]byte, updateNonceBytes)
	if _, err := rand.Read(b); err != nil {
		return "", fmt.Errorf("生成更新确认码失败: %w", err)
	}
	return hex.EncodeToString(b), nil
}

// prepareUpdateForChat stores a TTL-bound confirmation for this chat,
// message and user.
func prepareUpdateForChat(ctx context.Context, rel *ReleaseInfo, chatID int64, messageID int, userID int64) (*pendingUpdate, error) {
	p, err := buildPendingUpdate(ctx, rel)
	if err != nil {
		return nil, err
	}
	nonce, err := newUpdateNonce()
	if err != nil {
		return nil, err
	}
	p.Nonce = nonce
	p.ChatID = chatID
	p.MessageID = messageID
	p.UserID = userID
	storePendingUpdate(p)
	return p, nil
}

func storePendingUpdate(p *pendingUpdate) {
	pendingUpdates.Lock()
	defer pendingUpdates.Unlock()
	now := time.Now()
	for k, v := range pendingUpdates.m {
		if now.After(v.Expires) ||
			(v.ChatID == p.ChatID && v.MessageID == p.MessageID && v.UserID == p.UserID) {
			delete(pendingUpdates.m, k)
		}
	}
	pendingUpdates.m[p.Nonce] = p
}

// clearPendingUpdateFor invalidates confirmations for a menu bubble, e.g. when
// the user runs a fresh update check.
func clearPendingUpdateFor(chatID int64, messageID int, userID int64) {
	pendingUpdates.Lock()
	defer pendingUpdates.Unlock()
	for k, v := range pendingUpdates.m {
		if v.ChatID == chatID && v.MessageID == messageID && v.UserID == userID {
			delete(pendingUpdates.m, k)
		}
	}
}

// takePendingUpdate consumes a confirmation exactly once and verifies that it
// belongs to the same chat/message/user.
func takePendingUpdate(nonce string, chatID int64, messageID int, userID int64) *pendingUpdate {
	if nonce == "" {
		return nil
	}
	pendingUpdates.Lock()
	defer pendingUpdates.Unlock()
	p := pendingUpdates.m[nonce]
	if p == nil {
		return nil
	}
	if time.Now().After(p.Expires) {
		delete(pendingUpdates.m, nonce)
		return nil
	}
	if p.ChatID != chatID || p.MessageID != messageID || p.UserID != userID {
		return nil
	}
	delete(pendingUpdates.m, nonce)
	return p
}

func resetPendingUpdates() {
	pendingUpdates.Lock()
	pendingUpdates.m = make(map[string]*pendingUpdate)
	pendingUpdates.Unlock()
}

// installPreparedUpdate re-fetches the confirmed tag and verifies that the
// asset name and checksum still match before installing.
func installPreparedUpdate(ctx context.Context, p *pendingUpdate) (*updateResult, error) {
	if p == nil {
		return nil, fmt.Errorf("缺少更新确认信息")
	}
	rel, err := fetchReleaseByTag(ctx, p.Tag)
	if err != nil {
		return nil, err
	}
	if rel.TagName != p.Tag {
		return nil, fmt.Errorf("Release tag 不一致: 期望 %s，实际 %s", p.Tag, rel.TagName)
	}
	available, _, err := updateAvailability(version, rel.TagName)
	if err != nil {
		return nil, err
	}
	if !available {
		return nil, fmt.Errorf("当前版本 %s 已不低于 %s，取消安装", version, rel.TagName)
	}

	asset, err := findReleaseAsset(rel, p.AssetName)
	if err != nil {
		return nil, err
	}
	sums, err := fetchReleaseChecksums(ctx, rel)
	if err != nil {
		return nil, err
	}
	expected, ok := sums[p.AssetName]
	if !ok {
		return nil, fmt.Errorf("checksums.txt 中缺少 %s 的校验值，拒绝安装", p.AssetName)
	}
	if !strings.EqualFold(expected, p.Checksum) {
		return nil, fmt.Errorf("校验值已变化，拒绝安装（确认时 %s，当前 %s）", p.Checksum, expected)
	}

	execPath, err := executablePath()
	if err != nil {
		return nil, fmt.Errorf("获取可执行文件路径失败: %w", err)
	}
	temp, err := downloadAndVerify(ctx, *asset, p.Checksum, filepath.Dir(execPath))
	if err != nil {
		return nil, err
	}

	installed, backup, newPath, err := installBinary(temp, execPath)
	if err != nil {
		_ = os.Remove(temp)
		return nil, err
	}
	if !installed {
		return &updateResult{
			Version:       rel.TagName,
			ExecPath:      execPath,
			ManualReplace: true,
			NewPath:       newPath,
		}, nil
	}
	return &updateResult{
		Version:    rel.TagName,
		ExecPath:   execPath,
		BackupPath: backup,
	}, nil
}

// performUpdate is the convenience path used by tests and any non-interactive
// caller: check latest, then install the exact release that was checked.
func performUpdate(ctx context.Context) (*updateResult, error) {
	rel, err := fetchLatestRelease(ctx)
	if err != nil {
		return nil, err
	}
	p, err := buildPendingUpdate(ctx, rel)
	if err != nil {
		return nil, err
	}
	return installPreparedUpdate(ctx, p)
}

// createExecutableBackup copies the current executable into a fresh temp file
// in the same directory. It never follows a pre-existing .old symlink.
func createExecutableBackup(execPath string) (string, error) {
	src, err := os.Open(execPath)
	if err != nil {
		return "", err
	}
	defer src.Close()
	info, err := src.Stat()
	if err != nil {
		return "", err
	}
	if info.IsDir() {
		return "", fmt.Errorf("可执行文件路径是目录")
	}

	dst, err := os.CreateTemp(filepath.Dir(execPath), ".nodeseek-backup-*")
	if err != nil {
		return "", err
	}
	path := dst.Name()
	cleanup := func() {
		_ = dst.Close()
		_ = os.Remove(path)
	}
	if _, err := io.Copy(dst, src); err != nil {
		cleanup()
		return "", err
	}
	if err := dst.Sync(); err != nil {
		cleanup()
		return "", err
	}
	if err := dst.Close(); err != nil {
		_ = os.Remove(path)
		return "", err
	}
	if err := os.Chmod(path, info.Mode().Perm()); err != nil {
		_ = os.Remove(path)
		return "", err
	}
	return path, nil
}

// cleanupUpdateArtifacts removes stale backups and temp files from previous
// updates. It deliberately leaves Windows .new files alone because those are
// waiting for a manual replacement.
func cleanupUpdateArtifacts() {
	execPath, err := executablePath()
	if err != nil {
		return
	}
	dir := filepath.Dir(execPath)
	for _, pattern := range []string{".nodeseek-update-*", ".nodeseek-backup-*"} {
		matches, _ := filepath.Glob(filepath.Join(dir, pattern))
		for _, m := range matches {
			_ = os.Remove(m)
		}
	}
}
